// Mechanical fallback for any city not in the table above: strips accents/punctuation and takes the first
// three letters, padding with X if the name is too short (e.g. numbers-only or symbol-only names).
const FALLBACK_LETTERS = 3
export function mechanicalLoopCode(cityName) {
  const stripped = (cityName || '')
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z]/g, '').toUpperCase()
  const code = stripped.slice(0, FALLBACK_LETTERS)
  return code.padEnd(FALLBACK_LETTERS, 'X')
}

// The code to show for a city: its hand-picked entry above, or the mechanical fallback.
export function getCityLoopCode(cityName) {
  return cityLoopCodes[cityName] || mechanicalLoopCode(cityName)
}
