// The verb for a development's confirm dialog ("<verb> {name}?") and its build-cost button.
// Early Retirement is handled separately wherever this is used (it's "Purchase", and uses
// Reputation instead of a build cost), so it never needs to appear in LAUNCH_DEVELOPMENTS.
export function developmentVerb(name) {
    return LAUNCH_DEVELOPMENTS.has(name) ? 'Launch' : 'Build'
}

// Past tense of developmentVerb(), for the "<verb> on <date>" line on an already-owned development's
// card. Early Retirement is, again, handled separately by the caller ("Purchased"), same as above.
export function developmentVerbPast(name) {
    return LAUNCH_DEVELOPMENTS.has(name) ? 'Launched' : 'Built'
}
